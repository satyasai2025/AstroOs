# Test: Ephemeris service status detection
# ---------------------------------------------------------------------------

class TestEphemerisServiceStatus:
    """Validate that EphemerisService correctly detects .se1 vs Moshier."""

    def test_service_detects_official_mode(self, ephemeris_path):
        from apps.api.services.ephemeris_service import EphemerisService, EphemerisMode

        svc = EphemerisService(ephemeris_path)
        svc.initialize()
        status = svc.get_status()
        assert status.mode == EphemerisMode.OFFICIAL, (
            f"Expected OFFICIAL mode, got {status.mode}"
        )
        assert status.official_data is True
        assert len(status.se1_files) >= 3, (
            f"Expected at least 3 .se1 files, got {len(status.se1_files)}"
        )

    def test_service_detects_moshier_mode(self):
        from apps.api.services.ephemeris_service import EphemerisService, EphemerisMode

        svc = EphemerisService("/nonexistent/path")
        svc.initialize()
        status = svc.get_status()
        assert status.mode == EphemerisMode.MOSHIER, (
            f"Expected MOSHIER mode, got {status.mode}"
        )
        assert status.official_data is False
