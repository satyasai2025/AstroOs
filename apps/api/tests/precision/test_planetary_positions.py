"""
Precision tests: planetary position accuracy.

Validates that the Swiss Ephemeris wrapper produces positions within
< 1 arc-second of golden references computed from pyswisseph 2.10.03
with official .se1 data files (seas_18.se1, semo_18.se1, sepl_18.se1).

Golden references were generated by calling swe.calc_ut() directly and
are hardcoded below. If the .se1 files change (e.g. user installs a
different version), these tests will catch the drift.

Also validates that Moshier fallback positions are within a known
tolerance band (< 7 arc-seconds for most planets; Rahu/Ketu may be
less precise due to node interpolation).
"""

