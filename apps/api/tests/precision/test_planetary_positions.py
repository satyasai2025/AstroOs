# ---------------------------------------------------------------------------
# Test: Moshier fallback precision
# ---------------------------------------------------------------------------

class TestMoshierFallback:
    """
    Validate that Moshier fallback produces positions within known
    tolerance of official .se1. Also validates graceful degradation
    (no exceptions, results are usable).
    """

    def test_moshier_fallback_no_exception(self):
        """Moshier mode must not raise even without .se1 files."""
        swe.set_ephe_path("")  # No ephemeris files
        swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)
        # [1] = jd_ut. swe.calc_ut()/swe.houses() take Universal Time;
        # [0] is jd_et (Ephemeris Time) and is ~ΔT ahead.
        jd = swe.utc_to_jd(2000, 1, 7, 13, 30, 0, swe.GREG_CAL)[1]

        xx, retflag = swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)
        assert retflag >= 0, "Moshier fallback returned error"
        assert xx[0] > 0, "Moshier Sun longitude must be positive"
        # Restore path
        swe.set_ephe_path(os.environ.get("EPHEMERIS_PATH", ""))

    def test_moshier_fallback_within_tolerance(self, ephemeris_wrapper):
        """Moshier positions must be within pre-measured tolerance of .se1."""
        if not _check_se1_available():
            pytest.skip("Official .se1 files not available for comparison")

        # [1] = jd_ut. swe.calc_ut()/swe.houses() take Universal Time;
        # [0] is jd_et (Ephemeris Time) and is ~ΔT ahead.
        jd = swe.utc_to_jd(2000, 1, 7, 13, 30, 0, swe.GREG_CAL)[1]
        swe.set_ephe_path("")  # Force Moshier
        swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)

        planet_ids = {
            "sun": swe.SUN, "moon": swe.MOON, "mars": swe.MARS,
            "mercury": swe.MERCURY, "jupiter": swe.JUPITER,
            "venus": swe.VENUS, "saturn": swe.SATURN,
        }

        swe.set_ephe_path("")  # Moshier
        for name, pid in planet_ids.items():
            xx_mos, _ = swe.calc_ut(jd, pid, swe.FLG_MOSEPH | swe.FLG_SPEED)
            # Restore and get official
            swe.set_ephe_path(os.environ.get("EPHEMERIS_PATH", ""))
            swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)
            xx_off, _ = swe.calc_ut(jd, pid, swe.FLG_SWIEPH | swe.FLG_SPEED)

            diff_arcsec = abs(xx_off[0] - xx_mos[0]) * 3600.0
            tolerance = _MOSHIER_TOLERANCE_ARCSEC[name]
            assert diff_arcsec < tolerance, (
                f"{name} Moshier vs .se1 diff {diff_arcsec:.4f} arcsec "
                f"exceeds tolerance {tolerance}"
            )
            # Reset for next iteration
            swe.set_ephe_path("")

    def test_moshier_version_warning_message(self):
        """Verify that running without .se1 produces a detectable condition."""
        swe.set_ephe_path("")
        swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)
        # [1] = jd_ut. swe.calc_ut()/swe.houses() take Universal Time;
        # [0] is jd_et (Ephemeris Time) and is ~ΔT ahead.
        jd = swe.utc_to_jd(2000, 1, 7, 13, 30, 0, swe.GREG_CAL)[1]
        xx, retflag = swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)
        is_moshier = bool(retflag & swe.FLG_MOSEPH)
        assert is_moshier, "Expected Moshier mode when no .se1 files available"
        # Restore
        swe.set_ephe_path(os.environ.get("EPHEMERIS_PATH", ""))
        swe.set_sid_mode(swe.SIDM_LAHIRI, 0, 0)


