# Test: Tropical position accuracy with .se1
# ---------------------------------------------------------------------------

class TestTropicalPositions:
    """Validate tropical ecliptic longitudes against golden references."""

    @pytest.mark.parametrize(
        "planet,expected",
        list(_GOLDEN_TROPICAL_CASE1.items()),
        ids=[p for p in _GOLDEN_TROPICAL_CASE1],
    )
    def test_tropical_position_case1(
        self, ephemeris_wrapper, planet: str, expected: float
    ):
        if not _check_se1_available():
            pytest.skip("Official .se1 files not available")

        # [1] = jd_ut. swe.calc_ut()/swe.houses() take Universal Time;
        # [0] is jd_et (Ephemeris Time) and is ~ΔT ahead.
        jd = swe.utc_to_jd(2000, 1, 7, 13, 30, 0, swe.GREG_CAL)[1]
        pos = ephemeris_wrapper.get_planet_position(planet, jd)
        diff_arcsec = _deg_to_arcsec(pos.longitude - expected)
        assert diff_arcsec < _ARCSEC_TOLERANCE, (
            f"{planet} tropical longitude off by {diff_arcsec:.4f} arcsec "
            f"(got {pos.longitude:.6f}, expected {expected:.6f})"
        )


