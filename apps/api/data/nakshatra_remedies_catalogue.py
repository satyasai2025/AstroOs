def get_nakshatra_profile(nakshatra_name: str) -> Optional[NakshatraRemedyProfile]:
    """Retrieve the classical remedy profile for any nakshatra (case/format insensitive)."""
    if not nakshatra_name:
        return None
    key = nakshatra_name.lower().replace(" ", "_").replace("-", "_")
    return NAKSHATRA_CATALOGUE.get(key)
