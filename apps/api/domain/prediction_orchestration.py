@dataclass(frozen=True)
class TimeSlice:
    """A discrete temporal interval produced by the adaptive temporal scanner."""

    start_date: date
    end_date: date
    midpoint_datetime_utc: datetime
    resolution: TemporalResolution
    trigger_reason: str


@dataclass(frozen=True)
class SliceEvaluation:
    """Evaluated astrological intelligence on a single time slice."""

    slice: TimeSlice
    deterministic_score: int  # 0 to 100
    promise_status: PromiseStatus
    dasha_active: bool
    gochara_active: bool
    primary_triggers: tuple[str, ...] = field(default_factory=tuple)
    supporting_factors: tuple[str, ...] = field(default_factory=tuple)
    contradicting_factors: tuple[str, ...] = field(default_factory=tuple)
    evidence_trace: tuple[str, ...] = field(default_factory=tuple)
    technique_scores: dict[str, int] = field(default_factory=dict)


@dataclass(frozen=True)
class PredictionWindowCandidate:
    """A continuous temporal window of high consensus for event crystallization."""

    event_type: str
    start_date: date
    end_date: date
    peak_date: date
    peak_score: int  # 0 to 100
    promise_status: PromiseStatus
    primary_drivers: tuple[str, ...]
    supporting_factors: tuple[str, ...]
    opposing_factors: tuple[str, ...]
    evidence_trace: tuple[str, ...]
    resolution_level: TemporalResolution
    deterministic_hash: str


@dataclass(frozen=True)
class PredictionSynthesisResult:
    """Complete prediction report synthesized across the adaptive timeline."""

    event_type: str
    target_start_date: date
    target_end_date: date
    consensus_profile_used: ConsensusProfile
    candidate_windows: tuple[PredictionWindowCandidate, ...]
    total_slices_evaluated: int
    macro_slices_count: int
    refined_slices_count: int
    deterministic_signature: str
    summary: str