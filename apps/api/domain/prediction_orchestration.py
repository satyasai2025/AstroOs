"""
AstroOS — Prediction Orchestration Domain Contract

Defines the core data models for the deterministic Prediction Intelligence Engine:
  - ConsensusProfile: Configurable weights and conflict penalties
  - TimeSlice: Discrete temporal window generated by the adaptive scanner
  - SliceEvaluation: Technique triggers and deterministic score for a single slice
  - PredictionWindowCandidate: Narrowed temporal window of high consensus
  - PredictionSynthesisResult: Complete deterministic prediction synthesis report
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, datetime
from enum import Enum
from typing import Any, Optional


class TemporalResolution(str, Enum):
    MACRO_DASHA = "macro_dasha"
    MESO_GOCHARA = "meso_gochara"
    MICRO_INGRESS = "micro_ingress"


class PromiseStatus(str, Enum):
    ESTABLISHED = "established"
    WEAK = "weak"
    ABSENT = "absent"


@dataclass(frozen=True)
class ConsensusProfile:
    """Configurable and versioned weights for multi-technique consensus."""

    profile_id: str
    name: str
    version: str = "1.0"
    natal_promise_weight: float = 0.40
    dasha_weight: float = 0.35
    transit_weight: float = 0.25
    conflict_penalty_multiplier: float = 1.25
    minimum_activation_threshold: int = 60
    description: str = ""


